import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const tabs = await (await fetch('http://127.0.0.1:9338/json')).json();
const ws = new WebSocket(tabs.find(t => t.type === 'page').webSocketDebuggerUrl);
await new Promise(resolve => ws.addEventListener('open', resolve, {once:true}));
let id = 0; const pending = new Map(), errors = [];
ws.addEventListener('message', e => { const m = JSON.parse(e.data); if (m.id) { const p = pending.get(m.id); pending.delete(m.id); m.error ? p.reject(m.error) : p.resolve(m.result); } if (m.method === 'Runtime.exceptionThrown') errors.push(m.params.exceptionDetails.text); });
const call = (method, params = {}) => new Promise((resolve, reject) => { const next = ++id; pending.set(next, {resolve,reject}); ws.send(JSON.stringify({id:next,method,params})); });
const evaluate = async expression => { const r = await call('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true}); if(r.exceptionDetails) throw new Error(JSON.stringify(r.exceptionDetails)); return r.result.value; };
const wait = ms => new Promise(r => setTimeout(r,ms));
await call('Runtime.enable'); await call('Page.enable');
await call('Emulation.setDeviceMetricsOverride',{width:1280,height:720,deviceScaleFactor:1,mobile:false});
await call('Page.navigate',{url:'http://127.0.0.1:5182/instruments'});
await wait(800);
const target=await evaluate(`(()=>{const n=document.querySelector('.instrument-pick[tabindex="0"]');const r=n.getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2}})()`);
await call('Input.dispatchMouseEvent',{type:'mouseMoved',...target});
await wait(350);
assert.ok(await evaluate("new DOMMatrix(getComputedStyle(document.querySelector('.instrument-pick[tabindex=\"0\"] img')).transform).a>1.07"));
await call('Page.navigate',{url:'http://127.0.0.1:5182/ending'});
await wait(800);
await evaluate("document.querySelector('.site-menu-toggle').click()");
await wait(500);
await call('Page.captureScreenshot',{format:'png'}).then(r=>fs.writeFile('.tmp/feedback-ending.png',Buffer.from(r.data,'base64')));
await call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
await call('Page.navigate',{url:'http://127.0.0.1:5182/flag'});
await wait(800);
await evaluate("document.querySelector('.site-menu-toggle').click()");
await wait(500);
assert.ok(await evaluate("document.documentElement.scrollWidth<=innerWidth"));
await call('Page.captureScreenshot',{format:'png'}).then(r=>fs.writeFile('.tmp/feedback-mobile.png',Buffer.from(r.data,'base64')));
await call('Page.navigate',{url:'http://127.0.0.1:5182/experience?instrument=janggu'});
await wait(1000);
assert.equal(await evaluate("document.querySelectorAll('.site-menu').length"),0);
await call('Page.navigate',{url:'http://127.0.0.1:5182/'});
await wait(500);
assert.deepEqual(errors,[]);
console.log('PASS: instrument hover, ending layout, mobile width, menu absent in play');
await call('Browser.close');ws.close();
