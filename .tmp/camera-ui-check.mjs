import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const tabs = await (await fetch('http://127.0.0.1:9338/json')).json();
const ws = new WebSocket(tabs.find(t => t.type === 'page').webSocketDebuggerUrl);
await new Promise(resolve => ws.addEventListener('open', resolve, {once:true}));
let id = 0; const pending = new Map(), errors = [];
ws.addEventListener('message', e => { const m = JSON.parse(e.data); if (m.id) { const p = pending.get(m.id); pending.delete(m.id); m.error ? p.reject(m.error) : p.resolve(m.result); } if (m.method === 'Runtime.exceptionThrown') errors.push(m.params.exceptionDetails.text); });
const call = (method, params = {}) => new Promise((resolve, reject) => { const next = ++id; pending.set(next, {resolve,reject}); ws.send(JSON.stringify({id:next,method,params})); });
const evaluate = async expression => { const r = await call('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true}); if(r.exceptionDetails) throw new Error(JSON.stringify(r.exceptionDetails)); return r.result.value; };
const wait = ms => new Promise(r => setTimeout(r,ms));
await call('Runtime.enable'); await call('Page.enable');
await call('Emulation.setDeviceMetricsOverride',{width:1280,height:720,deviceScaleFactor:1,mobile:false});
await call('Page.navigate',{url:'http://127.0.0.1:5182/camera?instrument=janggu'});
await wait(3000);
assert.equal(await evaluate("document.querySelector('.camera-setup-start').disabled"),false);
assert.ok(await evaluate("document.querySelector('video').videoWidth > 0"));
const rect = await evaluate("(()=>{const r=document.querySelector('.camera-setup-preview').getBoundingClientRect();return {x:r.x,y:r.y,width:r.width,height:r.height}})()");
assert.ok(Math.abs(rect.x-747.357*1280/2240)<1);
assert.ok(Math.abs(rect.y-352.5*720/1260)<1);
await call('Page.captureScreenshot',{format:'png'}).then(r=>fs.writeFile('.tmp/camera-ui.png',Buffer.from(r.data,'base64')));
await evaluate("document.querySelector('.camera-setup-device-row button').click()");
await wait(2000);
assert.equal(await evaluate("document.querySelector('.camera-setup-start').disabled"),false);
await call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
await wait(300);
assert.ok(await evaluate("document.querySelector('.camera-setup-start').getBoundingClientRect().bottom < 844"));
assert.ok(await evaluate("document.querySelector('.camera-setup-preview').getBoundingClientRect().right <= 390"));
await call('Page.captureScreenshot',{format:'png'}).then(r=>fs.writeFile('.tmp/camera-ui-mobile.png',Buffer.from(r.data,'base64')));
await evaluate("document.querySelector('.camera-setup-start').click()");
await wait(100);
assert.ok((await evaluate('location.pathname')).includes('play-loading'));
assert.deepEqual(errors,[]);
console.log('PASS: Figma geometry, camera preview/reconnect, mobile layout, play-loading route, no runtime errors');
await call('Browser.close');
