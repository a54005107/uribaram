import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const tabs = await (await fetch('http://127.0.0.1:9338/json')).json();
const ws = new WebSocket(tabs.find(t => t.type === 'page').webSocketDebuggerUrl);
await new Promise(resolve => ws.addEventListener('open', resolve, {once:true}));
let id = 0; const pending = new Map(), errors = [];
ws.addEventListener('message', e => { const m = JSON.parse(e.data); if (m.id) { const p = pending.get(m.id); pending.delete(m.id); m.error ? p.reject(m.error) : p.resolve(m.result); } if (m.method === 'Runtime.exceptionThrown') errors.push(m.params.exceptionDetails.text); });
const call = (method, params = {}) => new Promise((resolve, reject) => { const next = ++id; pending.set(next, {resolve,reject}); ws.send(JSON.stringify({id:next,method,params})); });
const evaluate = async expression => { const r = await call('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true}); if(r.exceptionDetails) throw new Error(JSON.stringify(r.exceptionDetails)); return r.result.value; };
const wait = ms => new Promise(r => setTimeout(r,ms));
await call('Runtime.enable'); await call('Page.enable');
await call('Emulation.setDeviceMetricsOverride',{width:1280,height:720,deviceScaleFactor:1,mobile:false});
await call('Page.navigate',{url:'http://localhost:5182/trumpet'});
await wait(1000);
await evaluate("document.querySelector('.trumpet-instrument').click()");
await wait(100);
assert.equal(await evaluate("document.querySelectorAll('.trumpet-sparkle').length"),13);
await evaluate("document.querySelector('.trumpet-instrument').click()");
assert.ok(await evaluate("document.querySelector('.trumpet-progress').textContent.startsWith('1 / 3')"));
const sample=await evaluate(`(()=>{
 const nodes=[...document.querySelectorAll('.trumpet-sparkle')];
 nodes.forEach(n=>n.getAnimations().forEach(a=>{a.pause();a.currentTime=1000}));
 return nodes.map(n=>({opacity:getComputedStyle(n).opacity,transform:getComputedStyle(n).transform,loaded:n.firstChild.complete&&n.firstChild.naturalWidth>0}));
})()`);
assert.ok(sample.every(n=>Number(n.opacity)===1&&n.loaded));
assert.ok(sample.every(n=>n.transform==='matrix(1, 0, 0, 1, 0, 0)'));
const fall=await evaluate(`(()=>{
 const n=document.querySelector('.trumpet-sparkle');
 n.getAnimations().forEach(a=>a.currentTime=2100);
 return new DOMMatrix(getComputedStyle(n).transform).m42;
})()`);
assert.ok(Math.abs(fall)>10);
await call('Page.captureScreenshot',{format:'png'}).then(r=>fs.writeFile('.tmp/trumpet-motion.png',Buffer.from(r.data,'base64')));
await wait(2500);
assert.equal(await evaluate("document.querySelectorAll('.trumpet-sparkle').length"),0);
await evaluate("document.querySelector('.trumpet-instrument').click()");
await wait(2600);
await evaluate("document.querySelector('.trumpet-instrument').click()");
await wait(3200);
assert.equal(await evaluate('location.pathname'),'/flag');
assert.deepEqual(errors,[]);
console.log('PASS: 13 assets, hold/fall keyframes, duplicate click guard, three-click navigation, no runtime errors');
await call('Browser.close');ws.close();
