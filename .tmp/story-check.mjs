import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const tabs = await (await fetch('http://127.0.0.1:9338/json')).json();
const ws = new WebSocket(tabs.find(t => t.type === 'page').webSocketDebuggerUrl);
await new Promise(resolve => ws.addEventListener('open', resolve, {once:true}));
let id = 0; const pending = new Map(), errors = [];
ws.addEventListener('message', e => { const m = JSON.parse(e.data); if (m.id) { const p = pending.get(m.id); pending.delete(m.id); m.error ? p.reject(m.error) : p.resolve(m.result); } if (m.method === 'Runtime.exceptionThrown') errors.push(m.params.exceptionDetails.text); });
const call = (method, params = {}) => new Promise((resolve, reject) => { const next = ++id; pending.set(next, {resolve,reject}); ws.send(JSON.stringify({id:next,method,params})); });
const evaluate = async expression => { const r = await call('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true}); if(r.exceptionDetails) throw new Error(JSON.stringify(r.exceptionDetails)); return r.result.value; };
const wait = ms => new Promise(r => setTimeout(r,ms));
await call('Runtime.enable'); await call('Page.enable');
await call('Emulation.setDeviceMetricsOverride',{width:1280,height:720,deviceScaleFactor:1,mobile:false});
await call('Page.navigate',{url:'http://127.0.0.1:5182/ending'}); await wait(1000);
await evaluate('document.querySelector(".ending-story-link").click()'); await wait(1600);
assert.equal(await evaluate('location.pathname'),'/story');
await evaluate('document.fonts.ready');
assert.equal(await evaluate('document.querySelectorAll(".story-section").length'),8);
assert.equal(await evaluate('Array.from(document.querySelectorAll(".story-original-asset")).every(i => i.complete && i.naturalWidth > 0 && i.getBoundingClientRect().width > 1 && i.getBoundingClientRect().height > 1)'),true);
await call('Input.dispatchMouseEvent',{type:'mouseWheel',x:640,y:450,deltaX:0,deltaY:600}); await wait(300);
assert.ok(await evaluate('document.querySelector(".story-page").scrollTop') > 100);
assert.equal(await evaluate('location.pathname'),'/story');
await call('Emulation.setDeviceMetricsOverride',{width:1280,height:5292,deviceScaleFactor:1,mobile:false}); await wait(400);
await evaluate('document.querySelector(".story-page").scrollTop=0');
let shot=await call('Page.captureScreenshot');await fs.writeFile('.tmp/story-desktop.png',Buffer.from(shot.data,'base64'));
await call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:false});await wait(500);
assert.ok(await evaluate('document.querySelector(".story-page").scrollHeight > 844'));
assert.ok(await evaluate('document.querySelector(".story-page").scrollWidth <= 390'));
shot=await call('Page.captureScreenshot');await fs.writeFile('.tmp/story-mobile.png',Buffer.from(shot.data,'base64'));
await evaluate('document.querySelector(".story-page").scrollTop=document.querySelector(".story-page").scrollHeight');await wait(250);
shot=await call('Page.captureScreenshot');await fs.writeFile('.tmp/story-mobile-bottom.png',Buffer.from(shot.data,'base64'));
await evaluate('document.querySelector(\'[data-node-id="2570:3019"]\').click()');await wait(900);
assert.equal(await evaluate('location.pathname'),'/instruments');
assert.deepEqual(errors,[]);
console.log('PASS: ending -> story, 8 sections, all SVGs loaded, wheel scroll without route changes, mobile overflow, replay navigation, no runtime errors');
await call('Browser.close');ws.close();
