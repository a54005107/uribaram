import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const tabs = await (await fetch('http://127.0.0.1:9338/json')).json();
const ws = new WebSocket(tabs.find(t => t.type === 'page').webSocketDebuggerUrl);
await new Promise(resolve => ws.addEventListener('open', resolve, {once:true}));
let id = 0; const pending = new Map(), errors = [];
ws.addEventListener('message', e => { const m = JSON.parse(e.data); if (m.id) { const p = pending.get(m.id); pending.delete(m.id); m.error ? p.reject(m.error) : p.resolve(m.result); } if (m.method === 'Runtime.exceptionThrown') errors.push(m.params.exceptionDetails.text); });
const call = (method, params = {}) => new Promise((resolve, reject) => { const next = ++id; pending.set(next, {resolve,reject}); ws.send(JSON.stringify({id:next,method,params})); });
const evaluate = async expression => { const r = await call('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true}); if(r.exceptionDetails) throw new Error(JSON.stringify(r.exceptionDetails)); return r.result.value; };
const wait = ms => new Promise(r => setTimeout(r,ms));
await call('Runtime.enable'); await call('Page.enable');
await call('Emulation.setDeviceMetricsOverride',{width:1280,height:720,deviceScaleFactor:1,mobile:false});
await call('Page.navigate',{url:'http://127.0.0.1:5182/trumpet'});
await wait(1000);
assert.equal(await evaluate("document.querySelectorAll('.fullscreen-control').length"),0);
await evaluate("document.querySelector('.trumpet-instrument').click()");
await wait(300);
assert.equal(await evaluate("document.querySelectorAll('.trumpet-prototype-art [data-motion-keys]').length"),16);
assert.ok(await evaluate("[...document.querySelectorAll('.trumpet-prototype-art img')].every(i=>i.complete&&i.naturalWidth>0)"));
const motion=await evaluate(`(()=>{
 const first=document.querySelector('[data-node-id="2389:1513"]');
 const last=document.querySelector('[data-node-id="2389:1528"]');
 [first,last].forEach(n=>n.getAnimations().forEach(a=>{a.pause();a.currentTime=180}));
 return {first:getComputedStyle(first).scale,last:getComputedStyle(last).scale,staticAnimations:document.querySelector('.trumpet-prototype-art').getAnimations().length};
})()`);
assert.ok(parseFloat(motion.first)>1.09);
assert.equal(parseFloat(motion.last),1);
assert.equal(motion.staticAnimations,0);
await call('Page.captureScreenshot',{format:'png'}).then(r=>fs.writeFile('.tmp/trumpet-rings.png',Buffer.from(r.data,'base64')));
await wait(2400);
assert.equal(await evaluate("document.querySelectorAll('.trumpet-rings-active').length"),0);
await evaluate("document.querySelector('.trumpet-instrument').click()");
await wait(2600);
await evaluate("document.querySelector('.trumpet-instrument').click()");
await wait(3400);
assert.equal(await evaluate('location.pathname'),'/flag');
assert.deepEqual(errors,[]);
console.log('PASS: 16 rings, Figma stagger and 1.1 scale, static body, all assets, three-click route, no fullscreen UI');
await call('Browser.close');ws.close();
